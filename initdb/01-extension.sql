```sql
-- ============================================================================
-- PostgreSQL Extensions
-- This script is executed during database initialization.
-- ============================================================================

\echo 'Installing PostgreSQL extensions...'

------------------------------------------------------------------------------
-- UUID generation
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pgcrypto;

------------------------------------------------------------------------------
-- Query performance monitoring (PMM)
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

------------------------------------------------------------------------------
-- B-Tree support for GIN/GiST indexes
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS btree_gin;
CREATE EXTENSION IF NOT EXISTS btree_gist;

------------------------------------------------------------------------------
-- Case-insensitive text
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS citext;

------------------------------------------------------------------------------
-- Trigram search
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pg_trgm;

------------------------------------------------------------------------------
-- Fuzzy string matching
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS fuzzystrmatch;

------------------------------------------------------------------------------
-- Full-text search dictionaries
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS unaccent;

------------------------------------------------------------------------------
-- Key/value store
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS hstore;

------------------------------------------------------------------------------
-- XML support
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS xml2;

------------------------------------------------------------------------------
-- UUID support (legacy compatibility)
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

------------------------------------------------------------------------------
-- Additional statistics functions
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS tablefunc;

------------------------------------------------------------------------------
-- Admin utilities
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pg_visibility;
CREATE EXTENSION IF NOT EXISTS pg_freespacemap;

------------------------------------------------------------------------------
-- WAL inspection
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pg_walinspect;

------------------------------------------------------------------------------
-- Buffer cache inspection
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pg_buffercache;

------------------------------------------------------------------------------
-- Page inspection
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pageinspect;

------------------------------------------------------------------------------
-- Auto-vacuum monitoring
------------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pgstattuple;

\echo 'PostgreSQL extensions installed successfully.'
```
